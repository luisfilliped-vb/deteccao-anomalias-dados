precisao_regras = precision_score(y_real, y_previsto, zero_division=0)
recall_regras = recall_score(y_real, y_previsto, zero_division=0)
f1_regras = f1_score(y_real, y_previsto, zero_division=0)

print("EXPERIMENTO 1 - REGRAS TRADICIONAIS")
print("Anomalias detectadas:", y_previsto.sum())
print("Precisão:", round(precisao_regras, 4))
