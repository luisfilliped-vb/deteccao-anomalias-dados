import pandas as pd
import numpy as np

# Gerador de números aleatórios reproduzível
rng = np.random.default_rng(42)

# Produtos e preços de referência
produtos = {
    "Mouse": 50,
    "Teclado": 120,
    "Monitor": 900,
    "Headset": 200,
    "Webcam": 150
}

dados = []

# Criar 1.000 registros normais
for i in range(1, 1001):
    produto = rng.choice(list(produtos.keys()))
    preco = round(produtos[produto] * rng.uniform(0.9, 1.1), 2)
    quantidade = int(rng.integers(1, 11))

    dados.append({
        "id": i,
        "produto": produto,
        "preco": preco,
        "quantidade": quantidade,
        "anomalia": 0,
        "tipo_anomalia": "normal"
    })

df = pd.DataFrame(dados)

# Selecionar 50 registros sem repetição
indices = rng.choice(df.index, size=50, replace=False)

# Inserir 20 preços negativos
df.loc[indices[:20], "preco"] = -30.0
df.loc[indices[:20], "tipo_anomalia"] = "preco_negativo"

# Inserir 15 preços extremamente altos
df.loc[indices[20:35], "preco"] = 50000.0
df.loc[indices[20:35], "tipo_anomalia"] = "preco_alto"

# Inserir 15 quantidades extremamente altas
df.loc[indices[35:50], "quantidade"] = 1000
df.loc[indices[35:50], "tipo_anomalia"] = "quantidade_alta"

# Marcar as 50 anomalias
df.loc[indices, "anomalia"] = 1

# Verificar resultados
print("Total de registros:", len(df))
print("Registros normais:", (df["anomalia"] == 0).sum())
print("Registros anômalos:", (df["anomalia"] == 1).sum())

print("\nTipos de anomalia:")
print(df["tipo_anomalia"].value_counts())

print(df.head(10).to_string(index=False))

# Salvar o dataset
df.to_csv("vendas_experimento.csv", index=False)

import time
from sklearn.metrics import precision_score, recall_score, f1_score

inicio = time.perf_counter()

# Regras para detectar inconsistências e valores atípicos
preco_negativo = df["preco"] < 0
preco_muito_alto = df["preco"] > 10000
quantidade_muito_alta = df["quantidade"] > 100

# Um registro é sinalizado quando viola pelo menos uma regra
df["pred_regras"] = (
    preco_negativo |
    preco_muito_alto |
    quantidade_muito_alta
).astype(int)

tempo_regras = time.perf_counter() - inicio

# Comparar previsões com as anomalias conhecidas
y_real = df["anomalia"]
