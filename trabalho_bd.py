import time
import numpy as np
import pandas as pd
from sklearn.ensemble import IsolationForest
from sklearn.neighbors import LocalOutlierFactor
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import precision_score, recall_score, f1_score

# Funções auxiliares para manter a comparação reproduzível
precos_base = {"Mouse": 50, "Teclado": 120, "Monitor": 900, "Headset": 200, "Webcam": 150}
def preparar_X(base):
    atributos = pd.DataFrame({
        "preco_relativo": base["preco"] / base["produto"].map(precos_base),
        "quantidade": base["quantidade"]
    })
    return StandardScaler().fit_transform(atributos)

def metricas(y, pred):
    return (int(np.sum(pred)), precision_score(y, pred, zero_division=0),
            recall_score(y, pred, zero_division=0), f1_score(y, pred, zero_division=0))

def resumo_tempos(registros):
    t = pd.DataFrame(registros, columns=["Método", "Tempo (s)"])
    return t.groupby("Método")["Tempo (s)"].agg(["mean", "std", "median"]).round(6)

# 1) Dez repetições no dataset original, medindo apenas a aplicação/ajuste dos métodos
X = preparar_X(df)
resultados_tempo = []
for repeticao in range(10):
    inicio = time.perf_counter()
    pred_regras = ((df["preco"] < 0) | (df["preco"] > 10000) | (df["quantidade"] > 100)).astype(int)
    resultados_tempo.append(("Regras tradicionais", time.perf_counter() - inicio))

    modelo_if = IsolationForest(n_estimators=100, contamination=0.05, random_state=42)
    inicio = time.perf_counter()
    modelo_if.fit_predict(X)
    resultados_tempo.append(("Isolation Forest", time.perf_counter() - inicio))

    modelo_lof = LocalOutlierFactor(n_neighbors=20, contamination=0.05)
    inicio = time.perf_counter()
    modelo_lof.fit_predict(X)
    resultados_tempo.append(("LOF", time.perf_counter() - inicio))

print("=== TEMPOS: 10 REPETIÇÕES (DATASET ORIGINAL) ===")
print(resumo_tempos(resultados_tempo).to_string())
print("\n=== TEMPOS INDIVIDUAIS (s) ===")
print(pd.DataFrame(resultados_tempo, columns=["Método", "Tempo (s)"]).round(6).to_string(index=False))

# 2) Cenário de anomalias menos evidentes: sem valores negativos/extremos.
# Mantém os mesmos 50 rótulos verdadeiros, mas aproxima os valores dos normais.
df_sutil = df.copy()
rng_sutil = np.random.default_rng(123)
mask_neg = df_sutil["tipo_anomalia"].eq("preco_negativo")
mask_alto = df_sutil["tipo_anomalia"].eq("preco_alto")
mask_qtd = df_sutil["tipo_anomalia"].eq("quantidade_alta")
df_sutil.loc[mask_neg, "preco"] = (df_sutil.loc[mask_neg, "produto"].map(precos_base) * rng_sutil.uniform(1.18, 1.30, mask_neg.sum())).round(2)
df_sutil.loc[mask_alto, "preco"] = (df_sutil.loc[mask_alto, "produto"].map(precos_base) * rng_sutil.uniform(1.25, 1.40, mask_alto.sum())).round(2)
df_sutil.loc[mask_qtd, "quantidade"] = rng_sutil.integers(15, 31, mask_qtd.sum())

X_sutil = preparar_X(df_sutil)
y_sutil = df_sutil["anomalia"]
pred_regras_sutil = ((df_sutil["preco"] < 0) | (df_sutil["preco"] > 10000) | (df_sutil["quantidade"] > 100)).astype(int)
modelo_if_sutil = IsolationForest(n_estimators=100, contamination=0.05, random_state=42)
pred_if_sutil = (modelo_if_sutil.fit_predict(X_sutil) == -1).astype(int)
modelo_lof_sutil = LocalOutlierFactor(n_neighbors=20, contamination=0.05)
pred_lof_sutil = (modelo_lof_sutil.fit_predict(X_sutil) == -1).astype(int)

print("\n=== CENÁRIO SUTIL: MÉTRICAS ===")
for nome, pred in [("Regras tradicionais", pred_regras_sutil), ("Isolation Forest", pred_if_sutil), ("LOF", pred_lof_sutil)]:
    n, p, r, f = metricas(y_sutil, pred)
    print(f"{nome}: anomalias detectadas={n}; precisão={p:.4f}; recall={r:.4f}; F1-score={f:.4f}")
print("\n=== CONFIGURAÇÃO DO CENÁRIO SUTIL ===")
print("preços alterados para desvios aproximados de 18%-40% e quantidades entre 15 e 30; regras mantiveram limites <0, >10000 e >100")

